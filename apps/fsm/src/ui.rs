/// Where the *Download WinFsp* button goes (FR-APP-06).
pub const WINFSP_DOWNLOAD_URL: &str = "https://winfsp.dev/rel/";

/// What the user asked for.
#[derive(Debug, Clone, PartialEq)]
pub enum UiCommand {
    /// Open the dialog for a new profile.
    Add,
    /// Open the dialog on a profile.
    Edit(Uuid),
    /// Delete a profile. The user has been asked.
    Delete(Uuid),
    /// Take an unreadable entry out of the file. The user has been asked.
    DeleteUnreadable(UnreadableProfile),
    /// Mount a profile. *Mount all* sends one of these for each.
    Mount(Uuid),
    /// Unmount a profile. *Unmount all* sends one of these for each.
    Unmount(Uuid),
    /// Cancel a mount in progress.
    Cancel(Uuid),
    /// Open a drive's root (FR-MNT-12).
    OpenInExplorer(DriveLetter),
    /// Open the settings page.
    OpenSettings,
    /// Open [`WINFSP_DOWNLOAD_URL`].
    DownloadWinFsp,
    /// Esc with nothing left to close: hide to the tray (spec §7.7).
    HideWindow,
    /// The window's close button: hide to the tray or quit, by `close_to_tray` (FR-APP-02).
    CloseWindow,
}

struct Inner {
    window: slint::Weak<MainWindow>,
    commands: Box<dyn Fn(UiCommand)>,
    entries: Rc<VecModel<ListEntry>>,
    list: RefCell<ListState>,
    /// What the question on screen is about.
    deleting: RefCell<Option<Key>>,
    remembered: RefCell<Remembered>,
    remembered_path: Option<PathBuf>,
}

/// The main window, and what it needs to keep showing the right thing. Dropping it closes the window.
pub struct MainUi {
    window: MainWindow,
    inner: Rc<Inner>,
}

impl MainUi {
    /// Makes the window, not yet shown. Each thing the user asks for goes to `commands`, which is called
    /// on the UI thread, so it should only pass it on.
    ///
    /// # Errors
    /// There is no way to make a window.
    pub fn new(commands: impl Fn(UiCommand) + 'static) -> Result<Self, PlatformError> {
        let path = ConfigStore::default_path()
            .and_then(|config| Some(config.parent()?.join("ui-state.toml")));
        Self::with_remembered_path(commands, path)
    }

    /// As [`new`](Self::new), keeping what the window remembers in this file, or nowhere.
    ///
    /// # Errors
    /// There is no way to make a window.
    pub fn with_remembered_path(
        commands: impl Fn(UiCommand) + 'static,
        remembered_path: Option<PathBuf>,
    ) -> Result<Self, PlatformError> {
        let window = MainWindow::new()?;
        let remembered = remembered_path
            .as_deref()
            .map(Remembered::load)
            .unwrap_or_default();

        let entries = Rc::new(VecModel::default());
        window.set_entries(ModelRc::from(Rc::clone(&entries)));
        let inner = Rc::new(Inner {
            window: window.as_weak(),
            commands: Box::new(commands),
            entries,
            list: RefCell::new(ListState::new()),
            deleting: RefCell::new(None),
            remembered: RefCell::new(remembered),
            remembered_path,
        });
        connect(&window, &inner);
        inner.refresh();
        Ok(Self { window, inner })
    }

    /// Puts the window where it was, and shows it.
    ///
    /// # Errors
    /// The window cannot be shown.
    pub fn show(&self) -> Result<(), PlatformError> {
        self.inner.restore_placement();
        self.window.show()
    }

    /// The window itself.
    #[must_use]
    pub const fn window(&self) -> &MainWindow {
        &self.window
    }

    /// What the file holds now, at the start and after each Save or Delete.
    pub fn set_config(&self, config: Config) {
        self.inner.list.borrow_mut().set_config(config);
        self.inner.refresh();
    }

    /// A profile's new state.
    pub fn apply_event(&self, event: &MountEvent) {
        self.inner.list.borrow_mut().apply(event);
        self.inner.refresh();
    }

    /// Whether WinFsp can be used. If not, the banner shows, and nothing can start mounting
    /// (FR-APP-06).
    pub fn set_winfsp_ready(&self, ready: bool) {
        self.window.set_winfsp_missing(!ready);
        self.inner.list.borrow_mut().set_can_mount(ready);
        self.inner.refresh();
    }

    /// Why the file cannot be written, if it cannot (NFR-REL-05). Nothing can be added or deleted then.
    pub fn set_read_only(&self, reason: Option<&ReadOnlyReason>) {
        let text = reason.map_or_else(SharedString::new, |reason| {
            read_only_text(&self.window.global::<Texts>(), reason)
        });
        self.window.set_read_only_text(text);
        self.inner.list.borrow_mut().set_read_only(reason.is_some());
        self.inner.refresh();
    }

    /// The settings in the file that were not used.
    pub fn set_setting_problems(&self, problems: &[SettingProblem]) {
        let text = setting_problems_text(&self.window.global::<Texts>(), problems);
        self.window.set_settings_text(text);
    }

    /// The theme (FR-SET-03). *System* follows Windows.
    pub fn set_theme(&self, theme: Theme) {
        self.window.invoke_set_theme(match theme {
            Theme::System => ThemeChoice::System,
            Theme::Light => ThemeChoice::Light,
            Theme::Dark => ThemeChoice::Dark,
        });
    }
}

/// From what happens in the window to what it means.
fn connect(window: &MainWindow, inner: &Rc<Inner>) {
    let on = |action: fn(&Inner)| {
        let inner = Rc::clone(inner);
        move || action(&inner)
    };
    let on_row = |action: fn(&Inner, usize)| {
        let inner = Rc::clone(inner);
        move |index: i32| {
            if let Ok(index) = usize::try_from(index) {
                action(&inner, index);
            }
        }
    };

    window.on_add_pressed(on(Inner::add));
    window.on_mount_all_pressed(on(Inner::mount_all));
    window.on_unmount_all_pressed(on(Inner::unmount_all));
    window.on_settings_pressed(on(|inner| inner.send(UiCommand::OpenSettings)));
    window.on_download_winfsp_pressed(on(|inner| inner.send(UiCommand::DownloadWinFsp)));
    window.on_hide_pressed(on(Inner::hide));

    window.on_row_pressed(on_row(Inner::select));
    window.on_row_double_clicked(on_row(Inner::double_click));
    window.on_row_primary(on_row(Inner::primary_of));
    window.on_row_open(on_row(Inner::open_of));
    window.on_row_edit(on_row(Inner::edit_of));
    window.on_row_delete(on_row(Inner::ask_to_delete_at));

    window.on_activate_selected(on(Inner::activate_selected));
    window.on_open_selected(on(Inner::open_selected));
    window.on_edit_selected(on(Inner::edit_selected));
    window.on_delete_selected(on(Inner::delete_selected));

    let handler = Rc::clone(inner);
    window.on_move_selection(move |delta| {
        handler.list.borrow_mut().move_selection(delta);
        handler.refresh();
        handler.keep_selection_in_view();
    });
    let handler = Rc::clone(inner);
    window.on_question_answered(move |yes| handler.answer(yes));
    let handler = Rc::clone(inner);
    window.window().on_close_requested(move || {
        handler.remember_placement();
        handler.send(UiCommand::CloseWindow);
        CloseRequestResponse::KeepWindowShown
    });
}

impl Inner {
    fn send(&self, command: UiCommand) {
        (self.commands)(command);
    }

    fn add(&self) {
        if self.list.borrow().can_add() {
            self.send(UiCommand::Add);
        }
    }

    fn mount_all(&self) {
        let ids = self.list.borrow().mountable();
        for id in ids {
            self.send(UiCommand::Mount(id));
        }
    }

    fn unmount_all(&self) {
        let ids = self.list.borrow().unmountable();
        for id in ids {
            self.send(UiCommand::Unmount(id));
        }
    }

    fn hide(&self) {
        self.remember_placement();
        self.send(UiCommand::HideWindow);
    }

    /// The list item on this line. The model is only changed here on this thread, so it is the one the
    /// user acted on.
    fn item(&self, index: usize) -> Option<Item> {
        self.list.borrow().items().into_iter().nth(index)
    }

    fn selected_item(&self) -> Option<Item> {
        let list = self.list.borrow();
        let selected = list.selected()?;
        list.items().into_iter().find(|item| &item.key == selected)
    }

    fn select(&self, index: usize) {
        self.list.borrow_mut().select_place(index);
        self.refresh();
    }

    fn double_click(&self, index: usize) {
        let Some(Item {
            body: Body::Profile(row),
            ..
        }) = self.item(index)
        else {
            return;
        };
        if self.open(&row) {
            return;
        }
        if matches!(row.primary, Primary::Mount | Primary::Retry) {
            self.primary(&row);
        }
    }

    fn primary_of(&self, index: usize) {
        if let Some(Item {
            body: Body::Profile(row),
            ..
        }) = self.item(index)
        {
            self.primary(&row);
        }
    }

    /// The row's button, and Enter. Nothing if the button is disabled.
    fn primary(&self, row: &ProfileItem) {
        if !row.primary_enabled {
            return;
        }
        self.send(match row.primary {
            Primary::Mount | Primary::Retry => UiCommand::Mount(row.id),
            Primary::Cancel => UiCommand::Cancel(row.id),
            Primary::Unmount => UiCommand::Unmount(row.id),
        });
    }

    /// Returns whether it was mounted, and so opened.
    fn open(&self, row: &ProfileItem) -> bool {
        match row.letter {
            Some(letter) if row.can_open => {
                self.send(UiCommand::OpenInExplorer(letter));
                true
            }
            _ => false,
        }
    }

    fn open_of(&self, index: usize) {
        if let Some(Item {
            body: Body::Profile(row),
            ..
        }) = self.item(index)
        {
            self.open(&row);
        }
    }

    fn edit_of(&self, index: usize) {
        if let Some(Item {
            key: Key::Profile(id),
            ..
        }) = self.item(index)
        {
            self.send(UiCommand::Edit(id));
        }
    }

    fn activate_selected(&self) {
        if let Some(Body::Profile(row)) = self.selected_item().map(|item| item.body) {
            self.primary(&row);
        }
    }

    fn open_selected(&self) {
        if let Some(Body::Profile(row)) = self.selected_item().map(|item| item.body) {
            self.open(&row);
        }
    }

    fn edit_selected(&self) {
        if let Some(Key::Profile(id)) = self.selected_item().map(|item| item.key) {
            self.send(UiCommand::Edit(id));
        }
    }

    fn delete_selected(&self) {
        if let Some(item) = self.selected_item() {
            self.ask_to_delete(&item);
        }
    }

    fn ask_to_delete_at(&self, index: usize) {
        if let Some(item) = self.item(index) {
            self.ask_to_delete(&item);
        }
    }

    /// Asks first (FR-PROF-07), naming what else it does.
    fn ask_to_delete(&self, item: &Item) {
        let Some(window) = self.window.upgrade() else {
            return;
        };
        let texts = window.global::<Texts>();
        let question = match &item.body {
            Body::Profile(row) if !row.can_delete => return,
            Body::Profile(row) => {
                let name = SharedString::from(&row.name);
                match self.list.borrow().state_of(row.id) {
                    MountState::Connecting | MountState::Mounted | MountState::Unmounting => {
                        texts.invoke_delete_mounted_question(name)
                    }
                    MountState::Disconnected | MountState::Error(_) => {
                        texts.invoke_delete_question(name)
                    }
                }
            }
            Body::Unreadable {
                name, can_delete, ..
            } => {
                if !can_delete {
                    return;
                }
                let name = name
                    .as_ref()
                    .map_or_else(|| texts.invoke_unnamed(), SharedString::from);
                texts.invoke_delete_unreadable_question(name)
            }
        };
        *self.deleting.borrow_mut() = Some(item.key.clone());
        window.set_question(question);
    }

    fn answer(&self, yes: bool) {
        let key = self.deleting.borrow_mut().take();
        if let Some(window) = self.window.upgrade() {
            window.set_question(SharedString::new());
        }
        if !yes {
            return;
        }
        let command = match key {
            Some(Key::Profile(id)) => Some(UiCommand::Delete(id)),
            Some(Key::Unreadable(place)) => {
                let entry = self.list.borrow().unreadable(place).cloned();
                entry.map(UiCommand::DeleteUnreadable)
            }
            None => None,
        };
        if let Some(command) = command {
            self.send(command);
        }
    }

    fn save_remembered(&self) {
        if let Some(path) = &self.remembered_path {
            self.remembered.borrow().save(path);
        }
    }

    /// Notes where the window is. A minimized window has no useful place, and a maximized one keeps
    /// the place it goes back to.
    fn remember_placement(&self) {
        let Some(window) = self.window.upgrade() else {
            return;
        };
        let window = window.window();
        if window.is_minimized() {
            return;
        }
        {
            let mut remembered = self.remembered.borrow_mut();
            remembered.maximized = window.is_maximized();
            if !remembered.maximized {
                let position = window.position();
                let size = window.size().to_logical(window.scale_factor());
                remembered.placement = Some(Placement {
                    x: position.x,
                    y: position.y,
                    width: size.width,
                    height: size.height,
                });
            }
        }
        self.save_remembered();
    }

    /// Puts the window back, on a monitor that is still there.
    fn restore_placement(&self) {
        let Some(window) = self.window.upgrade() else {
            return;
        };
        let window = window.window();
        let remembered = self.remembered.borrow();
        if let Some(place) = remembered.placement {
            window.set_size(LogicalSize::new(place.width, place.height));
            let on_a_monitor = fsm_win::shell::is_on_a_monitor(
                place.x,
                place.y,
                place.width as u32,
                place.height as u32,
            );
            if on_a_monitor {
                window.set_position(PhysicalPosition::new(place.x, place.y));
            }
        }
        if remembered.maximized {
            window.set_maximized(true);
        }
    }

    fn keep_selection_in_view(&self) {
        if let Some(window) = self.window.upgrade() {
            window.invoke_ensure_selected_visible();
        }
    }

    /// Puts the list's state into the window. Only what changed is touched, so that a status event does
    /// not take the keyboard focus from a row's button.
    fn refresh(&self) {
        let Some(window) = self.window.upgrade() else {
            return;
        };
        let texts = window.global::<Texts>();
        let list = self.list.borrow();
        let items = list.items();
        let selected = list.selected_place();

        let mut top = 0.0;
        let mut selected_top = 0.0;
        let mut selected_height = 0.0;
        let entries: Vec<ListEntry> = items
            .iter()
            .enumerate()
            .map(|(place, item)| {
                let height = item.height();
                let entry = list_entry(&texts, item, top, height);
                if selected == Some(place) {
                    selected_top = top;
                    selected_height = height;
                }
                top += height;
                entry
            })
            .collect();
        update_model(&self.entries, entries);

        window.set_list_height(top);
        window.set_selected_index(
            selected
                .and_then(|place| i32::try_from(place).ok())
                .unwrap_or(-1),
        );
        window.set_selected_top(selected_top);
        window.set_selected_height(selected_height);
        window.set_no_connections(list.is_empty());
        window.set_can_add(list.can_add());
        window.set_can_mount_all(!list.mountable().is_empty());
        window.set_can_unmount_all(!list.unmountable().is_empty());

        let counts = list.counts();
        let number = |value: usize| i32::try_from(value).unwrap_or(i32::MAX);
        let parts: Vec<SharedString> = [
            (counts.mounted > 0).then(|| texts.invoke_count_mounted(number(counts.mounted))),
            (counts.connecting > 0)
                .then(|| texts.invoke_count_connecting(number(counts.connecting))),
            (counts.failed > 0).then(|| texts.invoke_count_failed(number(counts.failed))),
        ]
        .into_iter()
        .flatten()
        .collect();
        window.set_status_text(if parts.is_empty() {
            texts.invoke_nothing_mounted()
        } else {
            parts
                .iter()
                .map(SharedString::as_str)
                .collect::<Vec<_>>()
                .join(" · ")
                .into()
        });
    }
}

fn update_model(model: &VecModel<ListEntry>, entries: Vec<ListEntry>) {
    let kept = model.row_count().min(entries.len());
    while model.row_count() > entries.len() {
        model.remove(model.row_count() - 1);
    }
    for (place, entry) in entries.into_iter().enumerate() {
        if place >= kept {
            model.push(entry);
        } else if model.row_data(place).as_ref() != Some(&entry) {
            model.set_row_data(place, entry);
        }
    }
}

fn list_entry(texts: &Texts<'_>, item: &Item, top: f32, height: f32) -> ListEntry {
    let placed = ListEntry {
        top,
        height,
        ..ListEntry::default()
    };
    match &item.body {
        Body::Profile(row) => {
            let (line, line_is_problem) = line_text(texts, &row.line);
            ListEntry {
                kind: EntryKind::Profile,
                name: (&row.name).into(),
                address: (&row.address).into(),
                letter: row
                    .letter
                    .map(|letter| letter.to_string())
                    .unwrap_or_default()
                    .into(),
                letter_is_live: row.letter_is_live,
                status: match row.state {
                    MountState::Disconnected => RowStatus::Disconnected,
                    MountState::Connecting => RowStatus::Connecting,
                    MountState::Mounted => RowStatus::Mounted,
                    MountState::Unmounting => RowStatus::Unmounting,
                    MountState::Error(_) => RowStatus::Error,
                },
                line,
                line_is_problem,
                primary: match row.primary {
                    Primary::Mount => PrimaryAction::Mount,
                    Primary::Cancel => PrimaryAction::Cancel,
                    Primary::Unmount => PrimaryAction::Unmount,
                    Primary::Retry => PrimaryAction::Retry,
                },
                primary_enabled: row.primary_enabled,
                can_open: row.can_open,
                can_edit: true,
                can_delete: row.can_delete,
                ..placed
            }
        }
        Body::Unreadable {
            name,
            problem,
            can_delete,
        } => ListEntry {
            kind: EntryKind::Unreadable,
            name: name
                .as_ref()
                .map_or_else(|| texts.invoke_unnamed(), SharedString::from),
            status: RowStatus::Error,
            line: texts.invoke_unreadable_problem(problem.into()),
            line_is_problem: true,
            can_delete: *can_delete,
            ..placed
        },
    }
}

fn line_text(texts: &Texts<'_>, line: &Line) -> (SharedString, bool) {
    match line {
        Line::None => (SharedString::new(), false),
        Line::LetterMoved { letter, wanted } => (
            texts.invoke_letter_moved(letter.to_string().into(), wanted.to_string().into()),
            false,
        ),
        Line::NeedsCorrecting => (texts.invoke_needs_correcting(), true),
        Line::Failed(error) => (shown_error(texts, error).line(), true),
    }
}

